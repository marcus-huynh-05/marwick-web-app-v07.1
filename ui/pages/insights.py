import streamlit as st

from marwick.insights import PLANNED_INSIGHTS
from .. import components as c
from .. import state
from ..theme import esc, note, page_header, section

PLANNED_TITLES = {"frequency_vs_value": "Frequency vs average value", "recurring": "Recurring payments",
                  "unusual": "Unusual transactions"}


def _planned() -> None:
    section("Planned · not available yet")
    cols = st.columns(3)
    for col, (k, desc) in zip(cols, PLANNED_INSIGHTS.items()):
        with col:
            st.markdown(f'<div class="mw-planned"><div class="mw-insight-kind">Planned for v0.8</div>'
                        f'<div class="mw-insight-title">{esc(PLANNED_TITLES[k])}</div>'
                        f'<div class="mw-insight-text">{esc(desc.replace(" (v0.8)", ""))}.</div></div>',
                        unsafe_allow_html=True)


def render(d) -> None:
    page_header("Insights", "Insights",
                "Every insight is calculated by the engine and linked to its transactions. "
                "Nothing here is generated by AI.")
    if not isinstance(d, state.Data) or not d.ready:
        st.info("Insights appear once a file is loaded and two valid periods are selected.")
        st.button("Go to Analyse Spending", on_click=state.go, args=("Analyse Spending",))
        _planned()
        return
    c.periods_line(d)
    st.markdown('<div style="height:8px"></div>', unsafe_allow_html=True)
    c.comparison_warnings(d)
    n_review = int(d.tx["needs_review"].sum())
    if n_review:
        note(f"{n_review} transaction(s) still need review. Insights use the current classifications, "
             "so review them first for reliable results.", warn=True)
    if not d.insights:
        st.caption("No insights: both periods need transactions to compare.")
    else:
        head = [i for i in d.insights if i.kind == "net_change"]
        rest = [i for i in d.insights if i.kind != "net_change"]
        c.insight_grid(d, head, per_row=1, key="head")
        ups = [i for i in rest if (i.change or 0) > 0]
        downs = [i for i in rest if (i.change or 0) < 0]
        if ups:
            section(f"Spending increases ({len(ups)})")
            c.insight_grid(d, ups, per_row=2, key="up")
        if downs:
            section(f"Spending decreases ({len(downs)})")
            c.insight_grid(d, downs, per_row=2, key="down")
    _planned()
